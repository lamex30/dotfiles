# Alacritty: black background, all colors are shades of the accent (a gradient)
S_ = max(0.45, min(0.70, as_ * 0.95))
mono = {            # (hue shift, lightness): same hue family, different tones
    "blue":    (-0.030, 0.52), "red":    (-0.012, 0.60), "magenta": (0.000, 0.68),
    "green":   (+0.015, 0.74), "yellow": (+0.030, 0.80), "cyan":    (+0.020, 0.86),
}
normal = {k: hexc(ah + dh, L, S_) for k, (dh, L) in mono.items()}
bright = {k: hexc(ah + dh, min(L + 0.08, 0.93), S_ * 0.85) for k, (dh, L) in mono.items()}
normal["black"], bright["black"] = hexc(ah, 0.14, 0.12), hexc(ah, 0.45, 0.12)
normal["white"], bright["white"] = hexc(ah, 0.84, 0.10), hexc(ah, 0.95, 0.08)
order = ["black", "red", "green", "yellow", "blue", "magenta", "cyan", "white"]
