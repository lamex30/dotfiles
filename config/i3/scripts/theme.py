#!/usr/bin/env python3
"""Generate system colors from the wallpaper (i3, polybar, rofi, dunst, OSD).
Usage: theme.py [--force]   Returns exit code 0 if colors changed, 1 if unchanged."""
import colorsys, hashlib, json, os, sys, glob
from PIL import Image

HOME = os.path.expanduser("~")
CFG = f"{HOME}/.config"
walls = sorted(glob.glob(f"{CFG}/i3/wallpaper.*"))
if not walls: sys.exit(1)
WALL = walls[0]
STAMP = f"{CFG}/i3/.theme-stamp"

digest = hashlib.md5(open(WALL, "rb").read()).hexdigest()
if "--force" not in sys.argv and os.path.exists(STAMP) and open(STAMP).read() == digest:
    sys.exit(1)

img = Image.open(WALL).convert("RGB"); img.thumbnail((240, 240))
pal = img.quantize(colors=12, method=Image.Quantize.MEDIANCUT)
p = pal.getpalette()
counts = sorted(pal.getcolors(), reverse=True)
cols = [(n, tuple(c / 255 for c in p[i*3:i*3+3])) for n, i in counts]
total = sum(n for n, _ in cols)

def hls(c): return colorsys.rgb_to_hls(*c)
def hexc(h, l, s):
    r, g, b = colorsys.hls_to_rgb(h % 1, max(0, min(l, 1)), max(0, min(s, 1)))
    return "#%02x%02x%02x" % (round(r*255), round(g*255), round(b*255))

# base hue = most common color
bh, bl, bs = hls(cols[0][1])
# accent = most saturated, reasonably common, not too dark
def score(item):
    n, c = item; h, l, s = hls(c)
    v = max(c)
    return s * (n / total) ** 0.35 * (0.2 if v < 0.25 else 1)
ah, al, as_ = hls(max(cols, key=score)[1])
if as_ < 0.12:          # grayscale wallpaper -> soft neutral accent
    ah, as_ = bh, 0.25

c = {
    "bg":       hexc(bh, 0.08, min(bs, 0.30)),
    "bg_alt":   hexc(bh, 0.13, min(bs, 0.25)),
    "inactive": hexc(bh, 0.20, min(bs, 0.20)),
    "fg":       hexc(bh, 0.88, min(bs, 0.20)),
    "dim":      hexc(bh, 0.50, min(bs, 0.15)),
    "accent":   hexc(ah, 0.68, max(as_, 0.55)),
    "accent2":  hexc(ah + 0.08, 0.72, max(as_, 0.45)),
    "urgent":   hexc(0.98, 0.68, 0.80),
}

w = lambda path, text: (os.makedirs(os.path.dirname(path), exist_ok=True), open(path, "w").write(text))
w(f"{CFG}/i3/colors.json", json.dumps(c, indent=2))
w(f"{CFG}/i3/colors.conf", f"""# generated by theme.py from the wallpaper
client.focused          {c['accent']} {c['accent']} {c['bg']} {c['accent2']} {c['accent']}
client.focused_inactive {c['inactive']} {c['inactive']} {c['fg']} {c['inactive']} {c['inactive']}
client.unfocused        {c['bg']} {c['bg']} {c['dim']} {c['bg']} {c['bg']}
client.urgent           {c['urgent']} {c['urgent']} {c['bg']} {c['urgent']} {c['urgent']}
client.background       {c['bg']}
""")
w(f"{CFG}/polybar/colors.ini", "[colors]\n" + "".join(f"{k} = {c[k]}\n" for k in ("bg", "fg", "dim", "accent", "urgent")))
w(f"{CFG}/rofi/colors.rasi", "* {\n" + "".join(f"  {k.replace('_','-')}: {v};\n" for k, v in c.items()) + "}\n")
