# lock screen image: wallpaper scaled to the screen, blurred and darkened
try:
    from PIL import ImageFilter, ImageEnhance
    import re as _re
    try:
        import subprocess as _sp
        q = _sp.run(["xrandr", "--query"], capture_output=True, text=True).stdout
    except Exception: q = ""
    m = _re.search(r"current (\d+) x (\d+)", q)
    SW, SH = (int(m.group(1)), int(m.group(2))) if m else (1920, 1080)
    im = Image.open(WALL).convert("RGB")
    k = max(SW / im.width, SH / im.height)
    im = im.resize((round(im.width * k), round(im.height * k)), Image.LANCZOS)
    l, t = (im.width - SW) // 2, (im.height - SH) // 2
    im = im.crop((l, t, l + SW, t + SH)).filter(ImageFilter.GaussianBlur(12))
    ImageEnhance.Brightness(im).enhance(0.45).save(f"{CFG}/i3/lock.png")
except Exception as e:
    print("lock image:", e, file=sys.stderr)
